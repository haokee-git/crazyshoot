/* ------------------------------------------------------------------ *
 * 岩石露头：10 组手工轮廓，40 块交错旋转的 rock
 *
 * 全部落在场景之间的过渡带/边缘/干河床；避开公路（≥3 m，实测普遍 ≥8 m）、
 * 据点圈（≥r+6）、场景包络内部（只允许 ≤5 m 边缘咬合）。
 * 走向刻意不对称：西缘低脊、AB 峡谷齿、东走廊两块、北盆地、南缘板岩……
 * ------------------------------------------------------------------ */

type RockPiece = [x: number, z: number, w: number, d: number, rot: number, height: number];

function rockCluster(id: string, label: string, pieces: RockPiece[]): Cover[] {
  return pieces.map(([x, z, w, d, rot, height], index) =>
    cover('rock', x, z, w, d, rot, {
      id: `${id}-${index + 1}`,
      height,
      variant: 'pharaoh-rock',
      label,
    }),
  );
}

